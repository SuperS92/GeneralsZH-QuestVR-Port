"""Compile the optional full-image Quest TAA shaders to checked-in SPIR-V."""
import argparse, hashlib, pathlib, struct, subprocess
root=pathlib.Path(__file__).resolve().parents[3]
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--glslang',required=True,type=pathlib.Path)
args=parser.parse_args()
folder=root/'GeneralsMD/Code/Main/QuestVR'
header='// SPDX-License-Identifier: GPL-3.0-or-later\n// Generated by generate-taa-shaders.py; see RDR1-Quest-MIT.txt for resolve shader attribution.\n#pragma once\n#include <cstdint>\n'
temp=root/'work/taa-shaders'
temp.mkdir(parents=True,exist_ok=True)
for name,symbol in [('QuestTaaLite.vert','kTaaVertex'),('QuestTaaLite.frag','kTaaResolve'),('QuestTaaApply.frag','kTaaApply')]:
    source=folder/name;binary=pathlib.Path(temp)/(name+'.spv')
    subprocess.run([str(args.glslang),'-V','--target-env','vulkan1.0','-o',str(binary),str(source)],check=True)
    data=binary.read_bytes();words=struct.unpack('<'+'I'*(len(data)//4),data)
    header+='// '+name+' SHA256 '+hashlib.sha256(source.read_bytes()).hexdigest()+'\n'
    header+='static constexpr uint32_t '+symbol+'[] = {\n'
    header+=''.join('    '+', '.join(f'0x{v:08x}' for v in words[i:i+8])+',\n' for i in range(0,len(words),8))+'};\n'
(folder/'QuestTaaShaders.spv.h').write_text(header,encoding='utf-8',newline='\n')
