"""Generate the optional exact-pixel color transfer shader header."""
import argparse, hashlib, pathlib, struct, subprocess
root = pathlib.Path(__file__).resolve().parents[3]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--glslang', required=True, type=pathlib.Path)
args = parser.parse_args()
folder = root / 'GeneralsMD/Code/Main/QuestVR'
header = '// SPDX-License-Identifier: GPL-3.0-or-later\n// Generated by scripts/build/quest/generate-transfer-shaders.py.\n#pragma once\n#include <cstdint>\n'
temporary = root / 'work/color-transfer-shaders'
temporary.mkdir(parents=True, exist_ok=True)
for suffix, name in [('vert', 'Vertex'), ('frag', 'Fragment')]:
    source = folder / ('QuestColorTransfer.' + suffix)
    binary = temporary / (suffix + '.spv')
    subprocess.run([str(args.glslang), '-V', '--target-env', 'vulkan1.0', '-o', str(binary), str(source)], check=True)
    data = binary.read_bytes()
    words = struct.unpack('<' + 'I' * (len(data) // 4), data)
    header += '// GLSL SHA-256: ' + hashlib.sha256(source.read_bytes()).hexdigest() + '\n'
    header += 'static constexpr uint32_t kQuestColorTransfer' + name + '[] = {\n'
    header += ''.join('    ' + ', '.join(f'0x{word:08x}' for word in words[i:i+8]) + ',\n' for i in range(0, len(words), 8))
    header += '};\n'
(folder / 'QuestColorTransfer.spv.h').write_text(header, encoding='utf-8', newline='\n')
