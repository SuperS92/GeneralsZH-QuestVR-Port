"""Verify pinned original SMAA files and generate three Vulkan 1.0 compute shaders."""
import argparse, hashlib, json, pathlib, struct, subprocess, tempfile

root = pathlib.Path(__file__).resolve().parents[3]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--glslang', required=True, type=pathlib.Path)
args = parser.parse_args()
folder = root / 'GeneralsMD/Code/Main/QuestVR'
provenance = json.loads((folder / 'SMAA/PROVENANCE.json').read_text())
for name, expected in provenance['files'].items():
    actual = hashlib.sha256((folder / 'SMAA' / pathlib.PurePosixPath(name).name).read_bytes()).hexdigest()
    if actual != expected:
        raise SystemExit('Pinned SMAA source changed: ' + name)
source = folder / 'QuestSMAA.comp'
header = '// SPDX-License-Identifier: GPL-3.0-or-later\n// Generated by generate-smaa-shaders.py; original SMAA license in SMAA/LICENSE.txt.\n'
header += '// Wrapper SHA-256: ' + hashlib.sha256(source.read_bytes()).hexdigest() + '\n#pragma once\n#include <cstdint>\n'
with tempfile.TemporaryDirectory(prefix='quest-smaa-') as temp:
    for stage in range(3):
        binary = pathlib.Path(temp) / f'{stage}.spv'
        subprocess.run([str(args.glslang), '-V', '--target-env', 'vulkan1.0', f'-DSMAA_PASS={stage}',
            '-o', str(binary), str(source)], check=True)
        data = binary.read_bytes()
        words = struct.unpack('<' + 'I' * (len(data) // 4), data)
        header += f'static constexpr uint32_t kQuestSmaaStage{stage}[] = {{\n'
        header += ''.join('    ' + ', '.join(f'0x{word:08x}' for word in words[i:i+8]) + ',\n' for i in range(0, len(words), 8))
        header += '};\n'
        print('SMAA stage', stage, 'bytes', len(data), 'sha256', hashlib.sha256(data).hexdigest())
source.with_suffix('.spv.h').write_text(header, encoding='utf-8', newline='\n')
