"""Generate the checked-in optional Quest AA SPIR-V header with glslangValidator."""
import argparse, hashlib, pathlib, struct, subprocess, tempfile

root = pathlib.Path(__file__).resolve().parents[3]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--glslang', required=True, type=pathlib.Path)
args = parser.parse_args()
source = root / 'GeneralsMD/Code/Main/QuestVR/QuestSpatialAA.comp'
with tempfile.TemporaryDirectory(prefix='quest-aa-') as temp:
    binary = pathlib.Path(temp) / 'aa.spv'
    subprocess.run([str(args.glslang), '-V', '--target-env', 'vulkan1.0', '-o', str(binary), str(source)], check=True)
    data = binary.read_bytes()
    words = struct.unpack('<' + 'I' * (len(data) // 4), data)
header = '// SPDX-License-Identifier: GPL-3.0-or-later\n// Generated by scripts/build/quest/generate-aa-shader.py. Do not edit.\n'
header += '// GLSL SHA-256: ' + hashlib.sha256(source.read_bytes()).hexdigest() + '\n#pragma once\n#include <cstdint>\n'
header += 'static constexpr uint32_t kQuestSpatialAaShader[] = {\n'
header += ''.join('    ' + ', '.join(f'0x{word:08x}' for word in words[i:i+8]) + ',\n' for i in range(0, len(words), 8))
header += '};\n'
source.with_suffix('.spv.h').write_text(header, encoding='utf-8', newline='\n')
print('SPIR-V bytes:', len(data), 'sha256:', hashlib.sha256(data).hexdigest())
