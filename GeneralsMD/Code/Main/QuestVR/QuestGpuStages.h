#pragma once
#include <vulkan/vulkan.h>
namespace QuestXR {
// GeneralsX @performance Codex 16/10/2026 Precise scopes only for known native TAA resources; unknown accesses remain conservative.
inline VkPipelineStageFlags StagesForAccess(VkAccessFlags access,bool source) {
    constexpr VkAccessFlags known=VK_ACCESS_SHADER_READ_BIT|VK_ACCESS_COLOR_ATTACHMENT_READ_BIT|VK_ACCESS_COLOR_ATTACHMENT_WRITE_BIT
        |VK_ACCESS_DEPTH_STENCIL_ATTACHMENT_READ_BIT|VK_ACCESS_DEPTH_STENCIL_ATTACHMENT_WRITE_BIT|VK_ACCESS_TRANSFER_READ_BIT|VK_ACCESS_TRANSFER_WRITE_BIT;
    if(access&~known)return VK_PIPELINE_STAGE_ALL_COMMANDS_BIT;
    VkPipelineStageFlags stages=0;
    if(access&VK_ACCESS_SHADER_READ_BIT)stages|=VK_PIPELINE_STAGE_FRAGMENT_SHADER_BIT;
    if(access&(VK_ACCESS_COLOR_ATTACHMENT_READ_BIT|VK_ACCESS_COLOR_ATTACHMENT_WRITE_BIT))stages|=VK_PIPELINE_STAGE_COLOR_ATTACHMENT_OUTPUT_BIT;
    if(access&(VK_ACCESS_DEPTH_STENCIL_ATTACHMENT_READ_BIT|VK_ACCESS_DEPTH_STENCIL_ATTACHMENT_WRITE_BIT))stages|=VK_PIPELINE_STAGE_EARLY_FRAGMENT_TESTS_BIT|VK_PIPELINE_STAGE_LATE_FRAGMENT_TESTS_BIT;
    if(access&(VK_ACCESS_TRANSFER_READ_BIT|VK_ACCESS_TRANSFER_WRITE_BIT))stages|=VK_PIPELINE_STAGE_TRANSFER_BIT;
    return stages?stages:source?VK_PIPELINE_STAGE_TOP_OF_PIPE_BIT:VK_PIPELINE_STAGE_BOTTOM_OF_PIPE_BIT;
}
}
